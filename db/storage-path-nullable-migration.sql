-- القيد الأصلي في schema.sql كان storage_path "not null" — يمنع مسار
-- استنساخ الصوت المستقل الذي يتعمَّد عدم تخزين العيّنة الأصلية إطلاقًا
-- (بدل رفعها ثم حذفها لاحقًا). هذا التعديل يسمح بالقيمة الفارغة لهذا
-- السيناريو تحديدًا، بلا أي تأثير على العيّنات المرتبطة بمشاريع بودكاست
-- (تلك ستستمر بتخزين مسارها كالمعتاد).
alter table voice_samples
  alter column storage_path drop not null;
